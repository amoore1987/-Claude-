#!/usr/bin/env python3
"""Rebuild js/books-data.js from a live Shopify snapshot.

js/books-data.js is the single source the site, shorts/build_catalogue.py and
research/occasions read. It used to be a one-off scrape, so it drifted from the
store. This script makes the refresh repeatable:

    1. Pull active products from Shopify into data/shopify-snapshot.json
       (handle, title, type, price; creation order, oldest first).
    2. python3 build/refresh_catalogue.py
    3. python3 shorts/build_catalogue.py && python3 build/inline_artifact.py

What it keeps from the current file: `best` (hand-picked, filtered to live
handles), `reviews`, and each product's cover dimensions. `new` is the newest
ten books. Products with no local cover in assets/covers/ still render: the
site falls back to a branded title card until the cover is added.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "data" / "shopify-snapshot.json"
SITE_DATA = ROOT / "js" / "books-data.js"

GROUPS = {
    "Book": "books",
    "Customised Book": "custom",
    "Merchandise": "merch",
    "Book Bundle": "bundles",
}
NEW_COUNT = 10


def load_site_data() -> dict:
    src = SITE_DATA.read_text(encoding="utf-8")
    m = re.search(r"window\.JJ_DATA\s*=\s*(\{.*\})\s*;?\s*$", src, re.S)
    if not m:
        raise SystemExit(f"Could not find window.JJ_DATA in {SITE_DATA}")
    return json.loads(m.group(1))


def price(p: str) -> str:
    return f"{float(p):.2f}"


def main() -> None:
    snap = json.loads(SNAPSHOT.read_text(encoding="utf-8"))["products"]
    old = load_site_data()
    dims = {x["h"]: (x["w"], x["ht"]) for k in GROUPS.values() for x in old.get(k, [])}
    dims[old["club"]["h"]] = (old["club"]["w"], old["club"]["ht"])

    def item(p: dict) -> dict:
        w, ht = dims.get(p["handle"], (640, 640))
        return {"h": p["handle"], "t": p["title"], "p": price(p["price"]), "w": w, "ht": ht}

    data = {k: [] for k in GROUPS.values()}
    club = None
    # Newest first, which is how the library shelf has always been ordered.
    for p in reversed(snap):
        if p["type"] in GROUPS:
            data[GROUPS[p["type"]]].append(item(p))
        elif p["type"] == "Membership":
            club = item(p)
    if club is None:
        raise SystemExit("Snapshot has no Membership product for the book club")

    live_books = {b["h"] for b in data["books"]}
    best = [h for h in old.get("best", []) if h in live_books]
    dropped = [h for h in old.get("best", []) if h not in live_books]

    out = {
        "books": data["books"],
        "custom": data["custom"],
        "best": best,
        "new": [b["h"] for b in data["books"][:NEW_COUNT]],
        "merch": data["merch"],
        "bundles": data["bundles"],
        "club": club,
        "reviews": old.get("reviews", []),
    }
    SITE_DATA.write_text(
        "// Generated by build/refresh_catalogue.py from data/shopify-snapshot.json\n"
        "window.JJ_DATA = " + json.dumps(out, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    no_cover = [h for k in GROUPS.values() for h in (x["h"] for x in out[k])
                if not (ROOT / "assets" / "covers" / f"{h}.webp").exists()]
    print(f"Wrote {SITE_DATA.relative_to(ROOT)}: " + ", ".join(f"{len(out[k])} {k}" for k in GROUPS.values()))
    if dropped:
        print(f"  dropped from best (no longer live): {', '.join(dropped)}")
    if no_cover:
        print(f"  {len(no_cover)} without a local cover (title card shown): {', '.join(no_cover)}")


if __name__ == "__main__":
    main()
